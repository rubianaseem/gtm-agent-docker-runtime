"""Run every eval and write evals/results.json and evals/report.md.

  python run_evals.py            # routing eval + container checks + failure suite
  python run_evals.py --quick    # skip the failure suite

No API key, network or Docker needed. Model calls are not part of any eval.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from evals import container_checks, routing_eval  # noqa: E402


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args(argv)
    cases_text = (ROOT / "evals" / "cases_v1.json").read_bytes()
    want = (ROOT / "evals" / "cases_v1.sha256").read_text().split()[0]
    if hashlib.sha256(cases_text).hexdigest() != want:
        print("cases_v1.json does not match cases_v1.sha256; labels changed. Make a cases_v2 instead.")
        return 1
    res = {"cases_sha256": want, "routing": routing_eval.run(), "container": container_checks.run(),
           "docker_available": shutil.which("docker") is not None}
    if not a.quick:
        from evals import failure_suite
        res["failure_suite"] = failure_suite.run_all()
    (ROOT / "evals" / "results.json").write_text(json.dumps(res, indent=2))
    (ROOT / "evals" / "report.md").write_text(report(res))
    print(report(res))
    ok = all(r["passed"] for r in res.get("failure_suite", [])) and res["container"]["lint_repo"]["errors"] == 0
    return 0 if ok else 1


def report(r: dict) -> str:
    rt, bl = r["routing"]["runtime"], r["routing"]["baseline_country_only"]
    c = r["container"]
    L = ["# Eval report (generated by python run_evals.py)", "",
         f"cases_v1.json sha256 {r['cases_sha256'][:16]}... Docker on this machine: {r['docker_available']}", "",
         "## Routing decisions (cases_v1, synthetic)", "",
         "| split | runtime correct | baseline correct | review recall (rt / base) | unsafe auto-assign (rt / base) | injection obeyed (rt / base) |",
         "|---|---|---|---|---|---|"]
    for s in ("dev", "heldout", "all"):
        L.append(f"| {s} | {rt[s]['correct']}/{rt[s]['cases']} | {bl[s]['correct']}/{bl[s]['cases']} | "
                 f"{rt[s]['review_recall']} / {bl[s]['review_recall']} | {rt[s]['unsafe_auto_assign']} / "
                 f"{bl[s]['unsafe_auto_assign']} | {rt[s]['injection_obeyed']} / {bl[s]['injection_obeyed']} |")
    L += ["", f"Runtime misses: dev {rt['dev']['misses'] or 'none'}, held-out {rt['heldout']['misses'] or 'none'}", "",
          "## Container checks (static; no image is built by this command)", "",
          f"- Lint errors: this repo {c['lint_repo']['errors']} (warnings {c['lint_repo']['warnings']}); naive fixtures "
          f"{c['lint_naive']['errors']} ({', '.join(c['lint_naive']['ids'])})",
          f"- Build-context canary: {c['canary_repo']['canary_files_in_context']} of {c['canary_repo']['planted']} planted "
          f"secret files in the context with this .dockerignore; {c['canary_naive']['canary_files_in_context']} of "
          f"{c['canary_naive']['planted']} with the naive one",
          f"- COPY sources missing from the filtered context: {c['missing_copy_sources'] or 'none'}", ""]
    fs = r.get("failure_suite")
    if fs:
        L += [f"## Failure suite: {sum(x['passed'] for x in fs)}/{len(fs)} passed", "",
              "| id | scenario | result | key runtime numbers | naive baseline |", "|---|---|---|---|---|"]
        for x in fs:
            L.append(f"| {x['id']} | {x['name']} | {'PASS' if x['passed'] else 'FAIL'} | {_brief(x['runtime'])} | "
                     f"{_brief(x['baseline']) if x['baseline'] else 'n/a'} |")
    return "\n".join(L) + "\n"


def _brief(d) -> str:
    keys = ["writes", "expected_writes", "duplicate_effects", "unapproved_writes", "extra_writes_vs_clean_run",
            "first_exit", "exit", "requests", "log_lines_with_token", "plan_hash_mismatches", "lost_leads",
            "ops_parked", "stale_412_refusals", "l001_writes", "l002_writes", "refusals", "seconds_to_exit",
            "run_state", "new_writes", "new_plans", "leaks", "injected_text_in_outputs", "fresh", "stale", "fatal",
            "stopped", "missing", "torn_file", "retry_after_honoured", "cli_exit"]
    if not isinstance(d, dict):
        return str(d)
    if d and all(isinstance(v, dict) for v in d.values()):
        return "; ".join(f"{k}: {_brief(v)}" for k, v in d.items())
    return ", ".join(f"{k} {d[k]}" for k in keys if k in d).replace("|", "/")


if __name__ == "__main__":
    sys.exit(main())
